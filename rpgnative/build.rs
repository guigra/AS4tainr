//! The registry's build script (docs/native/adr/0003): include every
//! generated routine of `AS4TAINR_NATIVE_DIR` as a module and list them
//! in a table sorted by fingerprint. With the variable unset or empty
//! the registry is empty.

#![forbid(unsafe_code, unused_must_use)]
#![forbid(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::todo,
    clippy::unimplemented,
    clippy::indexing_slicing,
    clippy::string_slice,
    clippy::arithmetic_side_effects
)]

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The most generated routines one build includes: far above any
/// application, and a bound on what the build reads.
const MAX_ROUTINES: usize = 200_000;

/// A generated routine's file name is its fingerprint: 64 lower-case
/// hexadecimal digits, then `.rs`.
fn fingerprint_of(name: &str) -> Option<&str> {
    let fp = name.strip_suffix(".rs")?;
    (fp.len() == 64 && fp.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))).then_some(fp)
}

fn routines(dir: &Path) -> Result<Vec<(String, PathBuf)>, String> {
    let entries = std::fs::read_dir(dir)
        .map_err(|e| format!("AS4TAINR_NATIVE_DIR {}: {e}", dir.display()))?;
    let mut found = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|e| format!("AS4TAINR_NATIVE_DIR {}: {e}", dir.display()))?;
        let name = entry.file_name();
        let Some(name) = name.to_str() else { continue };
        let Some(fp) = fingerprint_of(name) else {
            continue;
        };
        if found.len() >= MAX_ROUTINES {
            return Err(format!(
                "AS4TAINR_NATIVE_DIR {}: more than {MAX_ROUTINES} generated routines",
                dir.display()
            ));
        }
        found.push((fp.to_string(), entry.path()));
    }
    found.sort();
    Ok(found)
}

fn generate(dir: Option<&Path>) -> Result<String, String> {
    let mut out = String::from("// Generated by rpgnative/build.rs. Do not edit.\n");
    writeln!(
        out,
        "/// The compiler this build uses (`rustc -V`).\npub const RUSTC_VERSION: &str = {:?};",
        rustc_version()?
    )
    .map_err(|e| e.to_string())?;
    let found = match dir {
        Some(d) => routines(d)?,
        None => Vec::new(),
    };
    for (fp, path) in &found {
        let path = path
            .canonicalize()
            .map_err(|e| format!("{}: {e}", path.display()))?;
        let path = path
            .to_str()
            .ok_or_else(|| format!("{}: not a UTF-8 path", path.display()))?;
        writeln!(out, "#[path = {path:?}]\nmod r_{fp};").map_err(|e| e.to_string())?;
    }
    out.push_str("/// Every generated routine, sorted by fingerprint.\n");
    out.push_str("pub static ROUTINES: &[(&str, rpgrt::native::RoutineFn)] = &[\n");
    for (fp, _) in &found {
        writeln!(out, "    ({fp:?}, r_{fp}::run),").map_err(|e| e.to_string())?;
    }
    out.push_str("];\n");
    Ok(out)
}

/// The compiler's version (`rustc -V`), part of every fingerprint: a
/// routine generated with one compiler is not taken by a build with
/// another (docs/native/adr/0002).
fn rustc_version() -> Result<String, String> {
    let rustc = std::env::var_os("RUSTC").ok_or("RUSTC is not set")?;
    let out = std::process::Command::new(&rustc)
        .arg("-V")
        .output()
        .map_err(|e| format!("rustc -V: {e}"))?;
    if !out.status.success() {
        return Err(format!("rustc -V: {}", out.status));
    }
    String::from_utf8(out.stdout)
        .map(|v| v.trim().to_string())
        .map_err(|e| format!("rustc -V: {e}"))
}

fn main() -> Result<(), String> {
    println!("cargo:rerun-if-env-changed=AS4TAINR_NATIVE_DIR");
    let dir = std::env::var_os("AS4TAINR_NATIVE_DIR")
        .filter(|d| !d.is_empty())
        .map(PathBuf::from);
    if let Some(d) = &dir {
        println!("cargo:rerun-if-changed={}", d.display());
    }
    let code = generate(dir.as_deref())?;
    let out = std::env::var_os("OUT_DIR").ok_or("OUT_DIR is not set")?;
    let file = Path::new(&out).join("programs.rs");
    std::fs::write(&file, code).map_err(|e| format!("{}: {e}", file.display()))
}
